export interface Book {
  /** 시리즈 번호 (1부터 빈틈없이) */
  no: number
  title: string
  author: string
  /** YYYY-MM-DD */
  pubDate: string
  aladinItemId: string
  images: { front: string; back: string; spine: string }
  /** 책등 이미지 가로/세로 */
  spineAspect: number
  /** 앞표지 이미지 가로/세로 */
  coverAspect: number
}

/**
 * 알라딘의 그 책 페이지. 상품 번호가 아직 없는 신간(출간 전이라 알라딘에 올라오지 않은 권)은
 * "서가명강 + 제목"으로 검색한 결과로 간다. 올라오면 `books`에 번호를 적는다.
 */
export const aladinUrl = (b: Pick<Book, 'aladinItemId' | 'title'>) =>
  b.aladinItemId
    ? `https://www.aladin.co.kr/shop/wproduct.aspx?ItemId=${b.aladinItemId}`
    : `https://www.aladin.co.kr/search/wsearchresult.aspx?SearchTarget=Book&SearchWord=${encodeURIComponent(`서가명강 ${b.title}`)}`

function book(
  no: number,
  title: string,
  author: string,
  pubDate: string,
  aladinItemId: string,
  spineAspect: number,
  coverAspect: number,
): Book {
  const nn = String(no).padStart(2, '0')
  return {
    no,
    title,
    author,
    pubDate,
    aladinItemId,
    images: {
      front: `/covers/${nn}_front.jpg`,
      back: `/covers/${nn}_back.jpg`,
      spine: `/covers/${nn}_spine.jpg`,
    },
    spineAspect,
    coverAspect,
  }
}

